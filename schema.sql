-- ============================================================================
-- HoneyShield Database Schema (MySQL 8 / InnoDB / utf8mb4)
-- ============================================================================

CREATE DATABASE IF NOT EXISTS `honeyshield`
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE `honeyshield`;

-- 1. users: Stores operator accounts with Argon2-hashed credentials and role-based permissions.
CREATE TABLE IF NOT EXISTS `users` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `email` VARCHAR(255) NOT NULL UNIQUE,
  `password_hash` VARCHAR(255) NOT NULL,
  `full_name` VARCHAR(100) NOT NULL,
  `role` VARCHAR(50) NOT NULL DEFAULT 'admin',
  `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  `failed_login_count` INT NOT NULL DEFAULT 0,
  `locked_until` DATETIME NULL,
  `last_login_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_users_email` (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. login_attempts: Records real and honeypot authentication telemetry with behavioral metrics.
CREATE TABLE IF NOT EXISTS `login_attempts` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `ip` VARCHAR(45) NOT NULL,
  `username` VARCHAR(255) NOT NULL,
  `password_hash_sha256` CHAR(64) NULL,
  `user_agent` TEXT NULL,
  `route` VARCHAR(255) NOT NULL,
  `status` ENUM('success', 'failed', 'blocked', 'bot_trap') NOT NULL,
  `is_honeypot` TINYINT(1) NOT NULL DEFAULT 0,
  `bot_trap_triggered` TINYINT(1) NOT NULL DEFAULT 0,
  `typing_speed_wpm` FLOAT NULL,
  `mouse_moves` INT NULL DEFAULT 0,
  `paste_detected` TINYINT(1) NULL DEFAULT 0,
  `time_to_submit_ms` INT NULL DEFAULT 0,
  `risk_score` INT NOT NULL DEFAULT 0,
  `classification` VARCHAR(50) NOT NULL DEFAULT 'normal',
  `rationale` VARCHAR(255) NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_login_ip_created` (`ip`, `created_at`),
  INDEX `idx_login_created` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. blocked_ips: Active and archived IP blocklist entries enforced by the firewall layer.
CREATE TABLE IF NOT EXISTS `blocked_ips` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `ip` VARCHAR(45) NOT NULL UNIQUE,
  `reason` VARCHAR(255) NOT NULL,
  `risk_score` INT NOT NULL DEFAULT 0,
  `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  `blocked_by_user_id` INT NULL,
  `unblocked_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_blocked_ip_created` (`ip`, `created_at`),
  CONSTRAINT `fk_blocked_user` FOREIGN KEY (`blocked_by_user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. alerts: High-priority threat detections generated by the risk classification engine.
CREATE TABLE IF NOT EXISTS `alerts` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `ip` VARCHAR(45) NULL,
  `severity` ENUM('low', 'medium', 'high', 'critical') NOT NULL DEFAULT 'medium',
  `title` VARCHAR(255) NOT NULL,
  `description` TEXT NOT NULL,
  `risk_score` INT NOT NULL DEFAULT 0,
  `is_reviewed` TINYINT(1) NOT NULL DEFAULT 0,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_alerts_ip_created` (`ip`, `created_at`),
  INDEX `idx_alerts_created` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. url_scans: SSRF-protected destination reconnaissance results, telemetry, and verdicts.
CREATE TABLE IF NOT EXISTS `url_scans` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `user_id` INT NULL,
  `target_url` TEXT NOT NULL,
  `ip_address` VARCHAR(45) NULL,
  `domain` VARCHAR(255) NOT NULL,
  `risk_score` INT NOT NULL DEFAULT 0,
  `verdict` VARCHAR(50) NOT NULL,
  `signals_json` LONGTEXT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_scans_ip_created` (`ip_address`, `created_at`),
  INDEX `idx_scans_domain` (`domain`),
  CONSTRAINT `fk_scans_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 6. tool_usage_log: Audit log of operator security toolkit invocations and query parameters.
CREATE TABLE IF NOT EXISTS `tool_usage_log` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `user_id` INT NULL,
  `ip` VARCHAR(45) NOT NULL,
  `tool_name` VARCHAR(50) NOT NULL,
  `query_summary` VARCHAR(255) NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX `idx_tool_ip_created` (`ip`, `created_at`),
  CONSTRAINT `fk_tool_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
